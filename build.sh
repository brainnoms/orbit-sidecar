#!/bin/bash
# Durable build for the orbit audio sidecar. Swift auto-links imported
# frameworks; listed explicitly here for resilience. Ad-hoc codesigned with
# the audio-input entitlement required for process taps.
set -euo pipefail
cd "$(dirname "$0")"
OUT="${1:-orbit-sidecar}"
# Compile-stamped version: SIDECAR_VERSION from the VERSION file (contract version,
# bump deliberately), SIDECAR_BUILD = git describe when available, else build timestamp.
# version.swift is GENERATED — never hand-edit; rebuild regenerates it.
VER="$(cat VERSION 2>/dev/null || echo 0.0.0-dev)"
GITDESC="$(git describe --always --dirty 2>/dev/null || true)"
BUILD="${GITDESC:-b$(date +%Y%m%d.%H%M)}"
printf '// GENERATED by build.sh — do not edit. Rebuild regenerates.\nlet SIDECAR_VERSION = "%s"\nlet SIDECAR_BUILD = "%s"\n' "$VER" "$BUILD" > version.swift
# multi-file swiftc requires top-level code in main.swift — orbit-sidecar.swift is
# the production source; the shim keeps it single-source-of-truth at build time.
# MediaRemote "Now Playing" adapter (vendored from nowplaying-cli, BSD-3).
# Compiled with clang into objects, then linked into the Swift binary; the
# ObjC `internal_get` is surfaced to Swift via orbit-mr-bridge.h.
MR_INC="-I mediaremote-mini -I mediaremote-mini/include -I mediaremote-mini/adapter -I mediaremote-mini/private -I mediaremote-mini/utility"
rm -f mr_*.o
for m in mediaremote-mini/adapter/*.m mediaremote-mini/private/MediaRemote.m mediaremote-mini/utility/helpers.m; do
  clang -c -fobjc-arc -O2 $MR_INC "$m" -o "mr_$(basename "${m%.m}").o"
done
# Now-Playing reader DYLIB — the sidecar reads the bus by exec'ing /usr/bin/perl
# (an Apple PLATFORM binary) to DynaLoader-load THIS dylib and call adapter_get_env.
# Our own non-platform binary cannot read the bus in-process (returns empty even in a
# GUI session — proven); the platform perl must be the requester. Same mechanism
# nowplaying-cli relies on. Vendored adapter (BSD-3, Jonas van den Berg).
clang -dynamiclib -fobjc-arc -O2 $MR_INC \
  mediaremote-mini/adapter/*.m mediaremote-mini/private/MediaRemote.m mediaremote-mini/utility/helpers.m \
  -o libOrbitNP.dylib -framework Foundation -framework AppKit -framework CoreServices -framework UniformTypeIdentifiers \
  -Wl,-exported_symbol,_adapter_get_env -Wl,-exported_symbol,_adapter_send_command
codesign --force --sign - libOrbitNP.dylib >/dev/null 2>&1 || true
cp orbit-sidecar.swift main.swift
swiftc -O main.swift channel-b.swift version.swift mr_*.o \
  -import-objc-header orbit-mr-bridge.h \
  -framework CoreAudio -framework AVFoundation -framework Network -framework CryptoKit -framework AppKit -framework UniformTypeIdentifiers \
  -o "$OUT"
rm -f main.swift mr_*.o
codesign --force --sign - --entitlements tap-entitlements.plist "$OUT"
# Reader artifacts must resolve next to the binary (see resolveHelperPaths() in Swift).
# Skip when OUT is built in-place (cwd) — they already live here.
OUTDIR="$(cd "$(dirname "$OUT")" 2>/dev/null && pwd || echo .)"
[ "$OUTDIR" != "$(pwd)" ] && cp -f mediaremote-mini.pl libOrbitNP.dylib "$OUTDIR/" 2>/dev/null || true
echo "[build] built + signed $(pwd)/$OUT @ $(date)"
codesign -d --entitlements - "$OUT" 2>/dev/null || true
